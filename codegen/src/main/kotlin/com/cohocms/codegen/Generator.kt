package com.cohocms.codegen

/** The language generated code is written in. */
enum class Language(val extension: String, val sourceRoot: String)
{
    JAVA("java", "src/main/java"),
    KOTLIN("kt", "src/main/kotlin"),
    ;

    companion object
    {
        fun of(name: String?): Language = when (name?.lowercase())
        {
            null, "", "java" -> JAVA
            "kotlin" -> KOTLIN
            else -> throw CodegenException("'$name' is not a language coho-codegen writes: set \"language\" to \"java\" or \"kotlin\"")
        }
    }
}

class GeneratedFile(
    /** Relative to the output directory. */
    val path: String,
    val contents: String,
)

class Generated(
    val files: List<GeneratedFile>,
    /** Things to tell whoever ran the generator. Never fatal. */
    val warnings: List<String>,
)

/** How every generated file starts, so a later run knows which files are its own to remove. */
const val GENERATED_MARK = "// Generated by coho-codegen from the Coho type model."

private const val HEADER = "$GENERATED_MARK Do not edit: run ./gradlew cohoGenerate."

private const val INDENT = "    "

/**
 * The code for a type model, in [language], in the package [packageName]: a class per content
 * type, such as `BlogPost`, one per component type, an interface per trait, and `Coho`, the
 * client whose reads return them.
 *
 * A pure function of the model, so the same model always gives the same bytes and a drift
 * check can compare them. Nothing about the generator's own version is written, for the same
 * reason.
 */
fun generate(model: TypeModel, packageName: String, language: Language): Generated
{
    val warnings = model.warnings.toMutableList()
    if (!model.source.immutable)
    {
        warnings += "Generated from '${model.source.ref}', a branch: its types can change. Release builds should name a tag."
    }
    val plan = Plan(model, warnings)
    val writer = when (language)
    {
        Language.JAVA -> JavaWriter(plan, packageName)
        Language.KOTLIN -> KotlinWriter(plan, packageName)
    }
    val files = buildList()
    {
        model.types.values.sortedBy { it.slug }.forEach { add(writer.type(it, component = false)) }
        model.components.values.sortedBy { it.slug }.forEach { add(writer.type(it, component = true)) }
        model.traits.values.sortedBy { it.slug }.forEach { add(writer.trait(it)) }
        add(writer.client())
    }
    // Two files a case-insensitive file system, such as macOS's or Windows', would write to one.
    files.groupBy { it.path.lowercase() }.values.firstOrNull { it.size > 1 }?.let()
    {
        throw CodegenException("${it[0].path} and ${it[1].path} would be one file on a case-insensitive file system; rename one of their types")
    }
    return Generated(files, warnings)
}

/** What both languages need to know about the model: names, families, and each field's shape. */
internal class Plan(val model: TypeModel, val warnings: MutableList<String>)
{
    private val all = model.types + model.components
    /** The names generated files define or import, which a type's class would hide. */
    private val reserved = setOf(
        "Asset", "ClientOptions", "Coho", "CompletableFuture", "ContentClient", "ContentConfig", "EntryBase", "EntryFactory",
        "EntryReader", "HydratedEntry", "ImageAsset", "ItemBase", "JsonNode", "Linked", "List", "Map", "NoOrder", "Nullable",
        "Object", "OffsetDateTime", "Override", "ReadOptions", "RepeaterItem", "SortBy", "SortOrder", "Source", "String", "TypeReader",
    )

    /** Each type's, component's and trait's class: `blogPost` is `BlogPost`. */
    val classes: Map<String, String> = buildMap()
    {
        val taken = HashSet<String>()
        for (type in (model.types.values + model.components.values + model.traits.values).sortedBy { it.slug })
        {
            var name = type.slug.replaceFirstChar { it.uppercase() }
            if (name in reserved)
            {
                warnings += "Type '${type.slug}' is named ${name}Entry, because $name is taken by the generated code."
                name = "${name}Entry"
            }
            if (!taken.add(name))
            {
                throw CodegenException("Two types would both be named $name; rename one of them")
            }
            put(type.slug, name)
        }
    }

    /** Each type's descendants, cycle-guarded: the server refuses a cycle, so this only stops a broken file. */
    private val below: Map<String, List<String>> = buildMap<String, MutableList<String>>()
    {
        for (type in all.values)
        {
            val seen = mutableSetOf(type.slug)
            var parent = type.extends
            while (parent != null && parent in all && seen.add(parent))
            {
                getOrPut(parent) { mutableListOf() }.add(type.slug)
                parent = all[parent]?.extends
            }
        }
    }

    fun isOpen(slug: String) = below[slug].orEmpty().isNotEmpty()

    fun parent(type: ContentType): ContentType? = type.extends?.let { all[it] }

    /** The fields a type declares itself: all of them, unless its parent is generated too. */
    fun inheritedFrom(type: ContentType): Set<String> = parent(type)?.fields?.map { it.id }?.toSet().orEmpty()

    /** The concrete types an entry can be. */
    val concrete = model.types.values.filter { !it.abstract }.sortedBy { it.slug }

    /** The class a reference to [targets] holds: their own, when one; any entry, when several or none. */
    fun target(targets: List<String>, base: String, untyped: String): String
    {
        val known = targets.filter { it in classes && it !in model.traits }.distinct()
        return when
        {
            known.isEmpty() -> untyped
            known.size == 1 -> classes.getValue(known[0])
            // Several, one of which the others extend: the base holds them all.
            else -> known.firstOrNull { root -> known.all { it == root || isBelow(it, root) } }?.let { classes.getValue(it) } ?: base
        }
    }

    private fun isBelow(slug: String, ancestor: String) = below[ancestor].orEmpty().contains(slug)

    /** Each field's name in code, by field id: its id, unless that is a keyword or taken. */
    fun properties(owner: String, fields: List<Field>): Map<String, String>
    {
        val out = LinkedHashMap<String, String>()
        val seen = HashMap<String, String>()
        for (field in fields)
        {
            var name = field.id
            if (name in RESERVED_PROPERTIES || name in KEYWORDS || !Regex("[A-Za-z_][A-Za-z0-9_]*").matches(name))
            {
                name = "${name.replace(Regex("[^A-Za-z0-9_]"), "_")}Value"
                warnings += "$owner.${field.id} is read as $name, because ${field.id} is taken."
            }
            seen.put(name.lowercase(), field.id)?.let { throw CodegenException("$owner: '$it' and '${field.id}' would both be $name; rename one of them") }
            out[field.id] = name
        }
        return out
    }

    /** Readers on `Coho`, by slug: the type's own name, unless the client already has one like it. */
    val readers: Map<String, String> = buildMap()
    {
        for (type in model.types.values.sortedBy { it.slug })
        {
            var member = type.slug
            if (member in CLIENT_MEMBERS || member in KEYWORDS)
            {
                warnings += "Type '${type.slug}' is read as coho.${member}Type, because coho.$member is taken."
                member = "${member}Type"
            }
            put(type.slug, member)
        }
    }

    fun note(field: Field, list: Boolean): String = listOfNotNull(
        if (field.kind == "choice" && field.values.isNotEmpty()) "One of ${listed(field.values, "or")}, or a value added since." else null,
        if (field.kind == "asset" && field.accept.isNotEmpty()) "Accepts ${field.accept.joinToString(", ")}." else null,
        if (field.kind == "asset" && !field.many) "Null where the asset it linked is gone." else null,
        if (field.kind == "longText" && field.textFormat == "markdown") "Markdown." else null,
        if (field.kind == "longText" && field.textFormat == "html") "HTML." else null,
        if (field.localized) "${if (list) "Empty" else "Null"} where the locale has no translation." else null,
    ).joinToString(" ")

    fun summary(type: ContentType, component: Boolean): String = listOfNotNull(
        if (component) "A repeater item, stored in the entry that holds it." else null,
        parent(type)?.let { "Extends ${classes.getValue(it.slug)}, and has every field it has." },
        if (type.abstract) "Abstract: ${if (component) "an item" else "an entry"} is one of the types that extend it." else null,
        traitsOf(type).takeIf { it.isNotEmpty() }?.let { "Has the trait${if (it.size == 1) "" else "s"} ${listed(it)}." },
    ).joinToString(" ")

    fun traitsOf(type: ContentType) = type.traits.mapNotNull { classes[it]?.takeIf { _ -> it in model.traits } }

    fun unknown(owner: String, field: Field)
    {
        warnings += "$owner.${field.id} is a '${field.kind}', which this generator does not know; it is read as JSON. Upgrade coho-codegen."
    }

    companion object
    {
        val RESERVED_PROPERTIES = setOf("id", "type", "slug", "locale", "fields", "javaClass", "class")
        val CLIENT_MEMBERS = setOf("content", "bySlug", "byId", "byIds", "bySlugAsync", "byIdAsync", "byIdsAsync")
        val KEYWORDS = setOf(
            // Java's
            "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue", "default", "do",
            "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if", "implements", "import", "instanceof",
            "int", "interface", "long", "native", "new", "package", "private", "protected", "public", "return", "short", "static",
            "strictfp", "super", "switch", "synchronized", "this", "throw", "throws", "transient", "try", "void", "volatile", "while",
            "true", "false", "null", "var", "record", "yield", "sealed", "permits",
            // Kotlin's hard keywords Java does not have
            "as", "fun", "in", "is", "object", "typealias", "typeof", "val", "when",
        )
        val RASTER_IMAGES = setOf("image/png", "image/jpeg", "image/gif", "image/webp", "image/avif", "image/heic")

        fun imageOnly(field: Field) = field.accept.isNotEmpty() && field.accept.all { it in RASTER_IMAGES }

        /** `A`, `A and B`, or `A, B, and C`; or with [conjunction] `or`. */
        fun listed(names: List<String>, conjunction: String = "and"): String = when (names.size)
        {
            0 -> ""
            1 -> names[0]
            2 -> "${names[0]} $conjunction ${names[1]}"
            else -> "${names.dropLast(1).joinToString(", ")}, $conjunction ${names.last()}"
        }

        /**
         * A one-line doc comment. Names are content, so a comment's end inside one is broken up, and
         * for Kotlin, whose comments nest, a comment's start too, as in a wildcard media type.
         */
        fun doc(name: String, note: String = "", nested: Boolean = false): String
        {
            var text = listOf(name.split(Regex("\\s+")).joinToString(" ").trim(), note).filter { it.isNotEmpty() }.joinToString(". ")
            text = text.replace("*/", "*&#47;")
            if (nested)
            {
                text = text.replace("/*", "/\\*")
            }
            return "/** $text */"
        }

        fun literal(value: String): String =
            "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\u0024").replace("\n", "\\n") + "\""

        /** `publishedAt` becomes `PUBLISHED_AT`. */
        fun constant(id: String): String = id.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").uppercase()
    }
}

/** One field's type and how its value is read, in one language. */
internal class Shape(val type: String, val read: String, val list: Boolean)

/** A language's writer. */
internal interface Writer
{
    fun type(type: ContentType, component: Boolean): GeneratedFile

    fun trait(trait: ContentType): GeneratedFile

    fun client(): GeneratedFile
}

/** The imports a file needs, by simple name, from the names its body uses. */
internal fun imports(body: String, available: Map<String, String>): List<String> =
    available.filterKeys { Regex("\\b$it\\b").containsMatchIn(body) }.values.sorted()

internal val RUNTIME_TYPES = listOf(
    "Asset", "ClientOptions", "ContentClient", "ContentConfig", "EntryBase", "EntryFactory", "EntryReader", "HydratedEntry",
    "ImageAsset", "ItemBase", "Linked", "NoOrder", "ReadOptions", "RepeaterItem", "SortOrder", "Source", "TypeReader",
).associateWith { "com.cohocms.delivery.$it" }
